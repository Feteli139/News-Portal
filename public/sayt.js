function normalizeBadWordText(value) {
  let text = String(value || "").toLowerCase().normalize("NFKC");
  const replacements = {
    "0":"o","1":"i","3":"e","4":"a","5":"s","7":"t","@":"a","$":"s","!":"i",
    "€":"e","ä":"a","ö":"o","ü":"u","ß":"ss","ı":"i","ş":"s","ğ":"g","ç":"c","ə":"e"
  };
  text = text.replace(/[013457@$!€äöüßışğçə]/g, c => replacements[c] || c);

  const cyrillicMap = {
    "а":"a","е":"e","о":"o","р":"p","с":"c","х":"x","у":"y","і":"i","к":"k","м":"m","т":"t","в":"b"
  };
  text = text.replace(/[аеорсхуікмтв]/g, c => cyrillicMap[c] || c);
  return text.replace(
    /([a-zа-яё\u0600-\u06ff\u4e00-\u9fff])[\s._*~\-]+(?=[a-zа-яё\u0600-\u06ff\u4e00-\u9fff])/gi,
    "$1"
  );
}

