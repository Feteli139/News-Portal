function isOneLetterDifferent(a, b) {
  if (!a || !b || Math.abs(a.length - b.length) > 1) return false;
  if (a === b) return true;
  if (Math.min(a.length,b.length) < 5) return false;

  let i=0,j=0,d=0;
  while(i<a.length && j<b.length) {
    if(a[i]===b[j]) { i++;j++; }
    else {
      if(++d>1) return false;
      if(a.length>b.length) i++;
      else if(b.length>a.length) j++;
      else { i++;j++; }
    }
  }
  if(i<a.length || j<b.length) d++;
  return d<=1;
}

function containsBadWord(value) {
  if(!value) return false;
  const text=normalizeBadWordText(value);
  for(const word of normalizedBadWords) {
    if(!word) continue;
    if(/[\u0600-\u06ff\u4e00-\u9fff]/.test(word)) {
      if(text.includes(word)) return true;
      continue;
    }
    const escaped=word.replace(/[.*+?^${}()|[\]\\]/g,"\\$&");
    if(new RegExp(`(^|[^a-zа-яё])${escaped}($|[^a-zа-яё])`,"i").test(text)) return true;
  }
  const tokens=text.match(/[a-z]+|[а-яё]+|[\u0600-\u06ff]+|[\u4e00-\u9fff]+/gi)||[];
  for(const token of tokens) {
    for(const word of normalizedBadWords) {
      if(word.length>=5 && isOneLetterDifferent(token,word)) return true;
    }
  }
  return false;
}

