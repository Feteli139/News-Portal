  function linkifyText(value) {
    const text=String(value||"");
    const urlRegex=/https?:\/\/[^\s<>"']+/gi;

    let result="";
    let lastIndex=0;
    let match;

    while((match=urlRegex.exec(text))!==null) {
      const originalUrl=match[0];

      let cleanUrl=originalUrl;
      let trailing="";

      while(/[.,!?;:)\]}]$/.test(cleanUrl)) {
        trailing=cleanUrl.slice(-1)+trailing;
        cleanUrl=cleanUrl.slice(0,-1);
      }

      let safeUrl="";

      try {
        const parsedUrl=new URL(cleanUrl);

        if(parsedUrl.protocol==="http:"||parsedUrl.protocol==="https:") {
          safeUrl=parsedUrl.href;
        }
      } catch(error) {
        safeUrl="";
      }

      result+=escapeHTML(text.slice(lastIndex,match.index));

      if(safeUrl) {
        result+=`
          <a href="${escapeHTML(safeUrl)}"
            target="_blank"
            rel="noopener noreferrer"
            style="color:#1683ff;text-decoration:underline;overflow-wrap:anywhere;">${escapeHTML(cleanUrl)}</a>${escapeHTML(trailing)}`;
      } else {
        result+=escapeHTML(originalUrl);
      }

      lastIndex=match.index+originalUrl.length;
    }

    result+=escapeHTML(text.slice(lastIndex));

    return result.replace(/\r?\n/g,"<br>");
  }

