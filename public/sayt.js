async function translateText(text, targetLang) {
    if (!text || targetLang === 'az') return text;
    try {
        const res = await fetch(`https://translate.googleapis.com/translate_a/single?client=gtx&sl=az&tl=${targetLang}&dt=t&q=${encodeURIComponent(text)}`);
        const data = await res.json();
        return data[0].map(item => item[0]).join('');
    } catch (err) {
        console.error("Tərcümə xətası:", err);
        return text;
    }
}

function changeLanguage(lang) {
    currentLang = lang;
    localStorage.setItem("lang", lang);
    
    const langSelect = document.getElementById("langSelect");
    if (langSelect) langSelect.value = lang;

    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (translations[lang] && translations[lang][key]) {
            el.placeholder = translations[lang][key];
        }
    });

    const adminSection = document.getElementById("adminSection");
    const adminBtn = document.getElementById("adminToggleButton");
    if (adminBtn && adminSection) {
        const isOpen = adminSection.style.display === "block";
        adminBtn.textContent = isOpen ? translations[currentLang].closePanelBtn : translations[currentLang].adminPanelBtn;
    }

    if (typeof renderCategoryButtons === "function") renderCategoryButtons();
    if (typeof renderNews === "function") renderNews();
}

function trackDailyUniqueVisit() {
    const todayDate = new Date().toISOString().split('T')[0];
    const lastVisitDate = localStorage.getItem('lastSiteVisitDate');

    if (lastVisitDate !== todayDate) {
        fetch('/api/site/daily-visit', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ date: todayDate })
        })
        .then(res => res.json())
        .then(data => {
            if (data.success) {
                localStorage.setItem('lastSiteVisitDate', todayDate);
            }
        })
        .catch(err => console.error("Ziyarət xətası:", err));
    }
}

